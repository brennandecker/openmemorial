import { readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../public/', import.meta.url));
const sizes = {};
function scan(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) scan(full);
    else if (entry.name.endsWith('.mp4')) sizes['/' + path.relative(root, full).split(path.sep).map(encodeURIComponent).join('/')] = statSync(full).size;
  }
}
scan(root);
writeFileSync(new URL('../src/videoSizes.ts', import.meta.url), '// Generated by scripts/generate-video-sizes.mjs.\nexport const videoSizes: Record<string, number> = ' + JSON.stringify(sizes, null, 2) + ';\n');
